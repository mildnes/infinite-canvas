// FileContent 获取文件内容。
func FileContent(w http.ResponseWriter, r *http.Request, id string) {
	started := time.Now()
	download, err := service.DownloadStorageObject(id, r.Header.Get("Range"))
	if err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			w.Header().Set("Cache-Control", "no-store")
			FailWithStatus(w, http.StatusNotFound, "文件不存在或已删除")
			return
		}
		FailError(w, err)
		return
	}
	defer download.Stream.Close()
	w.Header().Set("Server-Timing", "storage-open;dur="+strconv.FormatFloat(float64(time.Since(started).Microseconds())/1000, 'f', 1, 64))
	contentType := service.NormalizeStorageMIME(download.Object.MimeType)
	stream := bufio.NewReaderSize(download.Stream, 3072)
	if download.StatusCode != http.StatusPartialContent {
		prefix, _ := stream.Peek(3072)
		contentType, _ = service.NormalizeUploadedMIME(contentType, prefix)
	}
	w.Header().Set("X-Content-Type-Options", "nosniff")
	if !service.IsSupportedUploadedMIME(contentType) {
		contentType = "application/octet-stream"
		w.Header().Set("Content-Disposition", "attachment")
		w.Header().Set("Cache-Control", "no-store")
	} else {
		w.Header().Set("Cache-Control", "public, max-age=31536000, immutable")
	}
	w.Header().Set("Content-Type", contentType)
	if download.AcceptRanges {
		w.Header().Set("Accept-Ranges", "bytes")
	}
	if download.ContentRange != "" {
		w.Header().Set("Content-Range", download.ContentRange)
	}
	if download.ContentLength >= 0 {
		w.Header().Set("Content-Length", strconv.FormatInt(download.ContentLength, 10))
	}
	if download.StatusCode != 0 {
		w.WriteHeader(download.StatusCode)
	}
	_, _ = io.Copy(w, stream)
}

