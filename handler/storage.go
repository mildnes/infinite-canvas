// UploadFile 上传文件到对象存储。
func UploadFile(w http.ResponseWriter, r *http.Request) {
	user, ok := service.UserFromContext(r.Context())
	if !ok || user.ID == "" {
		Fail(w, "请先登录后再上传文件")
		return
	}
	reader, err := r.MultipartReader()
	if err != nil {
		Fail(w, "请选择要上传的文件")
		return
	}
	var provider *service.StorageObjectProviderInput
	for {
		part, err := reader.NextPart()
		if err != nil {
			Fail(w, "请选择要上传的文件")
			return
		}
		if part.FormName() == "provider" {
			raw, err := io.ReadAll(io.LimitReader(part, 4097))
			var parsed service.StorageObjectProviderInput
			if err != nil || len(raw) > 4096 || json.Unmarshal(raw, &parsed) != nil {
				Fail(w, "用户对象存储配置格式错误")
				return
			}
			provider = &parsed
			continue
		}
		if part.FormName() != "file" || part.FileName() == "" {
			continue
		}
		// Client provider fields precede the file. Authorize before reading its
		// bytes, rather than letting FormFile buffer the complete multipart body.
		if err := service.AuthorizeStorageUpload(r.Context(), provider); err != nil {
			FailError(w, err)
			return
		}
		data, err := io.ReadAll(part)
		if err != nil {
			FailError(w, err)
			return
		}
		object, err := service.UploadStorageObjectWithProvider(r.Context(), part.FileName(), part.Header.Get("Content-Type"), data, provider)
		if err != nil {
			FailError(w, err)
			return
		}
		OK(w, object)
		return
	}
}

// PersistGeneratedMedia stores authenticated generated bytes locally first.
// Optional cloud synchronization runs only after the stable server reference exists.
func PersistGeneratedMedia(w http.ResponseWriter, r *http.Request) {
	user, ok := service.UserFromContext(r.Context())
	if !ok || user.ID == "" {
		Fail(w, "请先登录")
		return
	}
	r.Body = http.MaxBytesReader(w, r.Body, (128<<20)+(1<<20))
	file, header, err := r.FormFile("file")
	if err != nil {
		Fail(w, "请选择生成媒体文件")
		return
	}
	defer file.Close()
	data, err := io.ReadAll(io.LimitReader(file, (128<<20)+1))
	if err != nil || len(data) == 0 || len(data) > 128<<20 {
		Fail(w, "生成媒体无效或超过 128MB")
		return
	}
	contentType := strings.TrimSpace(strings.Split(header.Header.Get("Content-Type"), ";")[0])
	if contentType == "" || contentType == "application/octet-stream" {
		contentType = strings.TrimSpace(strings.Split(http.DetectContentType(data), ";")[0])
	}
	if !service.IsSupportedGeneratedMediaMIME(contentType) {
		Fail(w, "生成媒体类型不受支持")
		return
	}
	if err := service.ValidateGeneratedMediaBytes(data, contentType); err != nil {
		FailError(w, err)
		return
	}
	sourceURL, _ := service.UnwrapGeneratedMediaSourceURL(r.FormValue("sourceUrl"))
	object, err := service.SaveGeneratedMediaDeduplicated(user.ID, contentType, data, sourceURL)
	if err != nil {
		FailError(w, err)
		return
	}
	if err := service.SyncGeneratedMedia(r.Context(), object.ID); err != nil {
		log.Printf("sync persisted generated media failed (local preserved): object=%s err=%v", object.ID, err)
	}
	OK(w, object)
}

