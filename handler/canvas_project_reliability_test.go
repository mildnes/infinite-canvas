package handler

import (
	"bytes"
	"context"
	"encoding/json"
	"net/http"
	"net/http/httptest"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
	"time"

	"github.com/tigerowo/infinite-canvas/config"
	"github.com/tigerowo/infinite-canvas/model"
	"github.com/tigerowo/infinite-canvas/repository"
	"github.com/tigerowo/infinite-canvas/service"
)

func TestCanvasProjectServerVersionsAndBulkDeletion(t *testing.T) {
	if os.Getenv("IC_CANVAS_PROJECT_RELIABILITY") != "1" {
		command := exec.Command(os.Args[0], "-test.run=^TestCanvasProjectServerVersionsAndBulkDeletion$", "-test.v")
		command.Env = append(os.Environ(), "IC_CANVAS_PROJECT_RELIABILITY=1")
		output, err := command.CombinedOutput()
		if err != nil {
			t.Fatalf("canvas project fixture: %v\n%s", err, output)
		}
		t.Logf("%s", output)
		return
	}
	config.Cfg.StorageDriver, config.Cfg.DatabaseDSN = "sqlite", filepath.Join(t.TempDir(), "canvas.db")
	database, err := repository.DB()
	if err != nil {
		t.Fatal(err)
	}
	ctx := service.WithUser(context.Background(), model.AuthUser{ID: "owner"})
	project := func(id, name string) map[string]any {
		return map[string]any{
			"id": id, "name": name, "nodes": []any{}, "connections": []any{},
			"createdAt": "2099-01-01T00:00:00Z", "updatedAt": "2099-01-01T00:00:00Z",
			"custom": json.RawMessage("9007199254740993"),
		}
	}
	call := func(handle http.HandlerFunc, body any) *httptest.ResponseRecorder {
		t.Helper()
		raw, err := json.Marshal(body)
		if err != nil {
			t.Fatal(err)
		}
		request := httptest.NewRequest(http.MethodPost, "/api/v1/canvas/projects", bytes.NewReader(raw)).WithContext(ctx)
		response := httptest.NewRecorder()
		handle(response, request)
		return response
	}
	readSaved := func(w *httptest.ResponseRecorder) map[string]json.RawMessage {
		t.Helper()
		var response struct {
			Code int
			Data map[string]json.RawMessage
		}
		if err := json.Unmarshal(w.Body.Bytes(), &response); err != nil || w.Code != http.StatusOK || response.Code != 0 {
			t.Fatalf("save response: status=%d body=%s err=%v", w.Code, w.Body, err)
		}
		return response.Data
	}
	stringField := func(data map[string]json.RawMessage, key string) string {
		var value string
		_ = json.Unmarshal(data[key], &value)
		return value
	}
	t.Run("timestamps are generated by the server", func(t *testing.T) {
		before := time.Now().UTC().Add(-time.Second)
		saved := readSaved(call(SaveUserCanvasProject, map[string]any{"data": project("clock", "new"), "baseUpdatedAt": ""}))
		for _, key := range []string{"createdAt", "updatedAt"} {
			stamp, err := time.Parse(time.RFC3339Nano, stringField(saved, key))
			if err != nil || stamp.Before(before) || stamp.After(time.Now().UTC().Add(time.Second)) {
				t.Errorf("%s trusts client time: %s", key, saved[key])
			}
		}
		if string(saved["custom"]) != "9007199254740993" {
			t.Error("unrelated payload number lost precision")
		}
	})
	t.Run("two editors receive an explicit conflict and canonical project", func(t *testing.T) {
		first := readSaved(call(SaveUserCanvasProject, map[string]any{"data": project("two-editors", "initial"), "baseUpdatedAt": ""}))
		base := stringField(first, "updatedAt")
		fromA := project("two-editors", "editor A")
		fromA["createdAt"] = "1900-01-01T00:00:00Z"
		updated := readSaved(call(SaveUserCanvasProject, map[string]any{"data": fromA, "baseUpdatedAt": base}))
		if stringField(updated, "createdAt") != stringField(first, "createdAt") || stringField(updated, "updatedAt") == base {
			t.Errorf("server version or createdAt not retained: first=%s updated=%s", first["updatedAt"], updated["updatedAt"])
		}
		stale := call(SaveUserCanvasProject, map[string]any{"data": project("two-editors", "editor B stale"), "baseUpdatedAt": base})
		var conflict struct {
			Code int
			Data struct {
				CurrentProject map[string]json.RawMessage `json:"currentProject"`
			}
		}
		_ = json.Unmarshal(stale.Body.Bytes(), &conflict)
		if stale.Code != http.StatusConflict || conflict.Code != 1 || stringField(conflict.Data.CurrentProject, "name") != "editor A" {
			t.Fatalf("stale edit did not return canonical conflict: status=%d body=%s", stale.Code, stale.Body)
		}
		readSaved(call(SaveUserCanvasProject, map[string]any{"data": project("two-editors", "editor B retry"), "baseUpdatedAt": stringField(conflict.Data.CurrentProject, "updatedAt")}))
		createAgain := call(SaveUserCanvasProject, map[string]any{"data": project("two-editors", "duplicate import"), "baseUpdatedAt": ""})
		if createAgain.Code != http.StatusConflict {
			t.Errorf("empty base overwrote existing project: status=%d body=%s", createAgain.Code, createAgain.Body)
		}
	})
	t.Run("sync uses server time and rolls back a conflicted batch", func(t *testing.T) {
		initial := readSaved(call(SaveUserCanvasProject, map[string]any{"data": project("sync-existing", "canonical"), "baseUpdatedAt": ""}))
		response := call(SyncUserCanvasProjects, map[string]any{
			"projects":       []any{project("sync-new", "must rollback"), project("sync-existing", "stale")},
			"baseUpdatedAts": map[string]string{"sync-new": "", "sync-existing": "stale-version"},
		})
		if response.Code != http.StatusConflict {
			t.Errorf("sync conflict returned status=%d body=%s", response.Code, response.Body)
		}
		var rows int64
		database.Model(&model.CanvasProject{}).Where("id = ?", "sync-new").Count(&rows)
		if rows != 0 {
			t.Error("conflicted batch leaked its preceding insert")
		}
		response = call(SyncUserCanvasProjects, map[string]any{
			"projects":       []any{project("sync-new", "new"), project("sync-existing", "updated")},
			"baseUpdatedAts": map[string]string{"sync-new": "", "sync-existing": stringField(initial, "updatedAt")},
		})
		if response.Code != http.StatusOK {
			t.Fatalf("fresh sync rejected: %s", response.Body)
		}
		var saved model.CanvasProject
		_ = database.First(&saved, "user_id = ? AND id = ?", "owner", "sync-new").Error
		if saved.UpdatedAt == "2099-01-01T00:00:00Z" {
			t.Error("sync persisted client timestamp")
		}
	})
	t.Run("legacy saves still work and user ownership remains isolated", func(t *testing.T) {
		readSaved(call(SaveUserCanvasProject, map[string]any{"data": project("legacy", "without base")}))
		foreign := service.WithUser(context.Background(), model.AuthUser{ID: "other-owner"})
		raw, _ := json.Marshal(project("legacy", "other owner"))
		if _, err := service.SaveCurrentUserCanvasProject(foreign, raw); err != nil {
			t.Fatal(err)
		}
		var rows int64
		database.Model(&model.CanvasProject{}).Where("id = ?", "legacy").Count(&rows)
		if rows != 2 {
			t.Errorf("same ID across owners was not isolated: rows=%d", rows)
		}
	})
	t.Run("bulk deletion is normalized, owner scoped, and cannot resurrect", func(t *testing.T) {
		for _, id := range []string{"delete-one", "delete-two", "keep"} {
			readSaved(call(SaveUserCanvasProject, map[string]any{"data": project(id, id), "baseUpdatedAt": ""}))
		}
		foreign := service.WithUser(context.Background(), model.AuthUser{ID: "other-owner"})
		raw, _ := json.Marshal(project("delete-one", "foreign"))
		if _, err := service.SaveCurrentUserCanvasProject(foreign, raw); err != nil {
			t.Fatal(err)
		}
		if err := service.DeleteCurrentUserCanvasProjects(ctx, []string{" ", " delete-one ", "delete-two", "delete-one"}); err != nil {
			t.Fatal(err)
		}
		projects, err := repository.ListUserCanvasProjects("owner")
		if err != nil {
			t.Fatal(err)
		}
		for _, saved := range projects {
			if saved.ID == "delete-one" || saved.ID == "delete-two" {
				t.Errorf("bulk deletion left %s alive", saved.ID)
			}
		}
		projects, err = repository.ListUserCanvasProjects("other-owner")
		if err != nil || len(projects) != 2 {
			t.Errorf("deletion crossed owners: projects=%v err=%v", projects, err)
		}
		if err := service.DeleteCurrentUserCanvasProjects(ctx, []string{"", " "}); err == nil {
			t.Error("empty batch should be rejected")
		}
		response := call(SaveUserCanvasProject, map[string]any{"data": project("delete-one", "resurrect"), "baseUpdatedAt": ""})
		if response.Code != http.StatusConflict {
			t.Errorf("deleted project did not yield conflict: status=%d body=%s", response.Code, response.Body)
		}
	})
}
